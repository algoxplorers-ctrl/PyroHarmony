-- 1. TABLA DE BIOMAS Y COEFICIENTES DE REGRESIÓN ORTOGONAL (α + β = 1.00)
CREATE TABLE IF NOT EXISTS public.pyroharmony_biomes (
  biome_id TEXT PRIMARY KEY,
  name_en TEXT NOT NULL,
  name_es TEXT NOT NULL,
  center_lat NUMERIC(6,2) NOT NULL,
  center_lon NUMERIC(6,2) NOT NULL,
  alpha_modis NUMERIC(4,2) NOT NULL,
  beta_viirs NUMERIC(4,2) NOT NULL,
  k_biome NUMERIC(4,2) NOT NULL,
  r_squared NUMERIC(4,2) NOT NULL,
  mbe_percent NUMERIC(5,2) NOT NULL,
  hotspot_ratio NUMERIC(4,2) NOT NULL,
  peak_week INTEGER NOT NULL,
  base_mean_mw NUMERIC(8,2) NOT NULL,
  base_std_mw NUMERIC(8,2) NOT NULL,
  agency_target TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT chk_scale_conservation CHECK (ROUND(alpha_modis + beta_viirs, 2) = 1.00),
  CONSTRAINT chk_quality_r2 CHECK (r_squared >= 0.85),
  CONSTRAINT chk_quality_mbe CHECK (ABS(mbe_percent) < 5.00)
);

-- 2. TABLA DE TELEMETRÍA ARMONIZADA Y Z-SCORE SEMANAL (MALLA 0.1° x 0.1°)
CREATE TABLE IF NOT EXISTS public.pyroharmony_telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  biome_id TEXT NOT NULL REFERENCES public.pyroharmony_biomes(biome_id) ON DELETE CASCADE,
  obs_year INTEGER NOT NULL CHECK (obs_year BETWEEN 2000 AND 2026),
  obs_week INTEGER NOT NULL CHECK (obs_week BETWEEN 1 AND 52),
  frp_modis_mw NUMERIC(10,2) NOT NULL,
  frp_viirs_scaled_mw NUMERIC(10,2) NOT NULL,
  frp_harmonized_mw NUMERIC(10,2) NOT NULL,
  count_modis_1000m INTEGER NOT NULL,
  count_viirs_375m INTEGER NOT NULL,
  z_score NUMERIC(5,2) NOT NULL,
  anomaly_tier TEXT NOT NULL,
  laces_posture TEXT NOT NULL,
  biomass_rate_kg_s NUMERIC(8,2) NOT NULL,
  synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. HABILITAR ROW LEVEL SECURITY (RLS) Y POLÍTICAS DE CIENCIA ABIERTA (FAIR)
ALTER TABLE public.pyroharmony_biomes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pyroharmony_telemetry ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read on biomes" ON public.pyroharmony_biomes;
CREATE POLICY "Allow public read on biomes"
  ON public.pyroharmony_biomes FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public read on telemetry" ON public.pyroharmony_telemetry;
CREATE POLICY "Allow public read on telemetry"
  ON public.pyroharmony_telemetry FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert on telemetry" ON public.pyroharmony_telemetry;
CREATE POLICY "Allow public insert on telemetry"
  ON public.pyroharmony_telemetry FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

